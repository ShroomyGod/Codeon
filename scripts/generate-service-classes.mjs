#!/usr/bin/env node
/**
 * Regenerates `src/shared/serviceClasses.ts` — the set of class names Roblox
 * offers as services — from Roblox's API dump.
 *
 *   node scripts/generate-service-classes.mjs [path/to/API-Dump.json]
 *
 * Without a path it downloads the current dump from the Roblox client tracker.
 * The set is generated because the Explorer needs to tell "a service Studio did
 * not list" from "an ordinary instance" (see src/shared/services.ts), and that
 * question is answered by the `Service` tag in the dump, not by guessing from
 * the class name. Re-run this after a Studio update that adds services.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const DUMP_URL = 'https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/API-Dump.json'
const here = dirname(fileURLToPath(import.meta.url))
const outFile = join(here, '..', 'src', 'shared', 'serviceClasses.ts')

async function loadDump(argument) {
  if (argument) return JSON.parse(readFileSync(resolve(argument), 'utf8'))
  console.log(`downloading ${DUMP_URL}`)
  const response = await fetch(DUMP_URL)
  if (!response.ok) throw new Error(`the API dump returned ${response.status}`)
  return response.json()
}

const dump = await loadDump(process.argv[2])
const names = dump.Classes.filter((entry) => (entry.Tags ?? []).includes('Service'))
  .map((entry) => entry.Name)
  .sort((a, b) => a.localeCompare(b))

if (names.length < 100) throw new Error(`only ${names.length} services found — that dump looks wrong`)

const source = `/**
 * Every class Roblox offers as a service.
 *
 * Generated by \`npm run services\` from Roblox's API dump (\`Tags: ["Service"]\`),
 * so it tracks new services instead of waiting for them to appear in a place and
 * surprise someone. Do not edit by hand — re-run the script after a Studio update.
 *
 * ${names.length} services.
 */
export const SERVICE_CLASSES: ReadonlySet<string> = new Set([
${names.map((name) => `  '${name}'`).join(',\n')}
])
`

writeFileSync(outFile, source)
console.log(`wrote ${names.length} service classes to ${outFile}`)
